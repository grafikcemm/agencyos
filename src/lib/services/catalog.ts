function offerPrice(offerId: string): { setup: number; monthly: number; days: number } {
  const o = findOfferById(offerId)
  if (!o) return { setup: 0, monthly: 0, days: 7 }
  return { setup: o.setupPrice, monthly: o.monthlyPrice, days: o.deliveryDays }
}

