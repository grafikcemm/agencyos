// ── Erişim yardımcıları ──────────────────────────────────────────────────────

const familyById = new Map(SERVICE_FAMILIES.map((f) => [f.id, f]))
const packageBySlug = new Map(SERVICE_PACKAGES.map((pkg) => [pkg.slug, pkg]))

export function findServiceBySlug(slug: string): ServicePackage | undefined {
  return packageBySlug.get(slug)
}

export function findFamilyById(id: string): ServiceFamily | undefined {
  return familyById.get(id)
}

export function domainOfPackage(pkg: ServicePackage): ServiceDomain {
  return familyById.get(pkg.familyId)?.domain ?? 'tasarim'
}

export function packagesByDomain(domain: ServiceDomain): ServicePackage[] {
  return SERVICE_PACKAGES.filter((pkg) => domainOfPackage(pkg) === domain)
}

// ── Compatibility adapter (SALT-OKUNUR) ─────────────────────────────────────
// Legacy offers.ts id'leri ve playbook adları → kanonik slug.
// offerMapping.resolveOfferId deseninin katalog karşılığı.

const legacyOfferMap = new Map<string, string>()
const legacyPlaybookMap = new Map<string, string>()
for (const pkg of SERVICE_PACKAGES) {
  for (const id of pkg.legacyOfferIds) legacyOfferMap.set(id, pkg.slug)
  for (const name of pkg.legacyPlaybookNames) legacyPlaybookMap.set(name.toLowerCase(), pkg.slug)
}

// Kanonik slug zaten verilmişse aynen döner; legacy offer id veya playbook adı
// ise kanonik slug'a çözer; tanınmıyorsa null (asla uydurma yok).
export function resolveServiceSlug(idOrName: string | null | undefined): string | null {
  if (!idOrName) return null
  const trimmed = idOrName.trim()
  if (packageBySlug.has(trimmed)) return trimmed
  const byOffer = legacyOfferMap.get(trimmed)
  if (byOffer) return byOffer
  return legacyPlaybookMap.get(trimmed.toLowerCase()) ?? null
}

